// ─────────────────────────────────────────────────────────────────────────────
// Static files (images / documents) for the static data layer.
//
// There is no file server: the seeded images are small SVG pictures and the
// seeded documents are one-page PDFs, both generated here as data: URLs.
// Files picked on screen get a blob: URL, so they preview and download
// during the session exactly like a stored file would.
// ─────────────────────────────────────────────────────────────────────────────

const b64 = (str) => {
  if (typeof btoa === "function") return btoa(unescape(encodeURIComponent(str)));
  return Buffer.from(str, "utf8").toString("base64");
};

const escXml = (s) => String(s ?? "").replace(/[<>&"']/g, (c) => ({ "<": "&lt;", ">": "&gt;", "&": "&amp;", '"': "&quot;", "'": "&#39;" }[c]));

const PALETTES = [
  ["#1d4ed8", "#60a5fa"], ["#0f766e", "#5eead4"], ["#7c3aed", "#c4b5fd"],
  ["#b45309", "#fcd34d"], ["#be123c", "#fda4af"], ["#334155", "#94a3b8"],
];

// A clean "equipment photo" placeholder: rack-unit faceplate drawn in SVG.
export function svgImage(title = "Image", subtitle = "", seed = 0, kind = "device") {
  const [c1, c2] = PALETTES[Math.abs(seed) % PALETTES.length];
  const units = kind === "site" ? "" : Array.from({ length: 4 }, (_, i) => `
    <g transform="translate(70 ${70 + i * 34})">
      <rect width="260" height="26" rx="3" fill="#0f172a" opacity="0.85"/>
      ${Array.from({ length: 10 }, (_, j) => `<rect x="${10 + j * 16}" y="7" width="11" height="12" rx="1.5" fill="#1e293b" stroke="#475569" stroke-width="0.8"/>`).join("")}
      <circle cx="232" cy="13" r="3.2" fill="${i === 2 ? "#f59e0b" : "#22c55e"}"/>
      <circle cx="246" cy="13" r="3.2" fill="#38bdf8"/>
    </g>`).join("");
  const site = kind === "site" ? `
    <g transform="translate(60 70)" fill="#ffffff" opacity="0.9">
      <rect x="0" y="40" width="90" height="100" rx="4"/><rect x="100" y="10" width="120" height="130" rx="4"/>
      <rect x="230" y="60" width="50" height="80" rx="4"/>
      ${Array.from({ length: 12 }, (_, j) => `<rect x="${112 + (j % 4) * 26}" y="${24 + Math.floor(j / 4) * 30}" width="16" height="18" fill="${c1}" opacity="0.55"/>`).join("")}
    </g>` : "";
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="400" height="300" viewBox="0 0 400 300">
  <defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${c1}"/><stop offset="1" stop-color="${c2}"/></linearGradient></defs>
  <rect width="400" height="300" fill="url(#g)"/>${units}${site}
  <rect x="0" y="228" width="400" height="72" fill="#0f172a" opacity="0.55"/>
  <text x="20" y="258" font-family="Segoe UI, Arial, sans-serif" font-size="19" font-weight="700" fill="#fff">${escXml(title).slice(0, 34)}</text>
  <text x="20" y="282" font-family="Segoe UI, Arial, sans-serif" font-size="13" fill="#e2e8f0">${escXml(subtitle).slice(0, 48)}</text>
</svg>`;
  return { base64: b64(svg), dataUrl: `data:image/svg+xml;base64,${b64(svg)}`, mime: "image/svg+xml" };
}

// Minimal one-page PDF (Helvetica text) as a data: URL.
export function pdfDocument(title = "Document", lines = []) {
  const ascii = (s) => String(s ?? "").replace(/[^\x20-\x7E]/g, "-");
  const esc = (s) => ascii(s).replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");
  const body = [
    "BT", "/F1 20 Tf", "56 780 Td", `(${esc(title)}) Tj`, "/F1 11 Tf",
    ...lines.flatMap((l) => ["0 -24 Td", `(${esc(l)}) Tj`]),
    "0 -40 Td", "/F1 9 Tf", "(Static demo document - generated by the DCIM portal.) Tj", "ET",
  ].join("\n");
  const objs = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    `<< /Length ${body.length} >>\nstream\n${body}\nendstream`,
  ];
  let pdf = "%PDF-1.4\n";
  const offsets = [];
  objs.forEach((o, i) => { offsets.push(pdf.length); pdf += `${i + 1} 0 obj\n${o}\nendobj\n`; });
  const xref = pdf.length;
  pdf += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n` + offsets.map((o) => `${String(o).padStart(10, "0")} 00000 n \n`).join("");
  pdf += `trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`;
  const base64 = typeof btoa === "function" ? btoa(pdf) : Buffer.from(pdf, "latin1").toString("base64");
  return { base64, dataUrl: `data:application/pdf;base64,${base64}`, mime: "application/pdf" };
}

// ── registry: file id → URL (used by the preview / download helpers) ────────
const registry = new Map();

export function registerFileUrl(id, url) {
  if (id !== undefined && id !== null && url) registry.set(String(id), url);
}

export function fileUrlById(id) {
  const u = registry.get(String(id));
  if (!u) return null;
  // data: URLs cannot be opened in a new tab, so hand out a blob: URL instead
  if (u.startsWith("data:") && typeof URL !== "undefined" && URL.createObjectURL) {
    const blobUrl = URL.createObjectURL(dataUrlToBlob(u));
    registry.set(String(id), blobUrl);
    return blobUrl;
  }
  return u;
}

// File picked in the browser → URL that works for <img>, <iframe> and download
export function urlForUpload(file) {
  try {
    if (typeof File !== "undefined" && file instanceof Blob) return URL.createObjectURL(file);
  } catch { /* ignore */ }
  return null;
}

export const isInlineUrl = (u) => typeof u === "string" && /^(data:|blob:)/i.test(u);

// data: URL → Blob (no fetch involved)
export function dataUrlToBlob(dataUrl) {
  const m = String(dataUrl || "").match(/^data:([^;,]+)?(;base64)?,(.*)$/);
  if (!m) return new Blob([]);
  const mime = m[1] || "application/octet-stream";
  if (m[2]) {
    const bin = atob(m[3]);
    const bytes = new Uint8Array(bin.length);
    for (let i = 0; i < bin.length; i += 1) bytes[i] = bin.charCodeAt(i);
    return new Blob([bytes], { type: mime });
  }
  return new Blob([decodeURIComponent(m[3])], { type: mime });
}
